#!/usr/bin/env node
'use strict';
// Turns one business's details (template/replica.config.example.json) into the files an
// owner needs to set that business up on the platform. It validates with the same rules the
// database enforces, writes files, and does nothing else: no network, no database, no secrets.
//
//   npm run new:business -- path/to/config.json [outDir]
//
// Output (default template/out/<slug>/, git-ignored):
//   01-provision.sql             run once in the Supabase SQL editor (provision_tenant is service-role only)
//   02-operator-app-checklist.md exact values for Settings in the Operator app (those functions need a signed-in admin)
//   03-website-and-links.md      website address, domain routing entry, driver and operator links

const fs = require('fs');
const path = require('path');

const SLUG = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const HEX = /^#[0-9a-fA-F]{6}$/;
const CODE = /^[A-Za-z]{3,4}$/;
const SECRETISH = /(secret|password|passwd|token|api[_-]?key|service[_-]?role|sk_live|sk_test|whsec_|private[_-]?key)/i;
const SECRET_VALUE = /(sk_(live|test)_|whsec_|re_[A-Za-z0-9]{10,}|eyJ[A-Za-z0-9_-]{20,}\.)/;

function walk(v, p, out) {
  if (v && typeof v === 'object') {
    for (const [k, x] of Object.entries(v)) {
      if (SECRETISH.test(k) && !k.startsWith('_')) out.push(`${p}${k}: looks like a secret field; never put keys or passwords in this file`);
      walk(x, `${p}${k}.`, out);
    }
  } else if (typeof v === 'string' && SECRET_VALUE.test(v)) out.push(`${p.replace(/\.$/, '')}: looks like a key or token; remove it`);
}

function host(u) { return String(u || '').toLowerCase().replace(/^https?:\/\//, '').replace(/^www\./, '').replace(/[/?#].*$/, ''); }

function validate(c) {
  const e = [];
  if (!c || typeof c !== 'object') return ['The config must be a JSON object.'];
  walk(c, '', e);
  const slug = String(c.slug || '');
  if (!SLUG.test(slug) || slug.length > 40) e.push('slug: lowercase letters, numbers and hyphens, up to 40 characters.');
  const name = String(c.name || '').trim();
  if (!name || name.length > 100) e.push('name: required, up to 100 characters.');
  if (c.contact_email && !EMAIL.test(String(c.contact_email).trim())) e.push('contact_email: not a valid email address.');
  if (c.contact_phone && !/^\+?[0-9 ]{7,20}$/.test(String(c.contact_phone))) e.push('contact_phone: digits and spaces only, optionally starting with +.');
  if (c.website) {
    if (!/^https:\/\/[a-z0-9.-]+\.[a-z]{2,}\/?$/i.test(String(c.website))) e.push('website: must look like https://www.example.co.uk');
    else if (/(^|\.)(winjodigital\.co\.uk|winjo-dispatch\.vercel\.app)$/.test(host(c.website))) e.push('website: that domain belongs to the platform.');
  }
  const b = c.branding || {};
  for (const k of ['primary', 'accent']) if (b[k] && !HEX.test(b[k])) e.push(`branding.${k}: must be a colour like #0B132B.`);
  const p = c.pricing || {};
  const extra = p.extra_stop === undefined ? 0 : Number(p.extra_stop);
  if (!(extra >= 0 && extra <= 500)) e.push('pricing.extra_stop: between 0 and 500.');
  const list = Array.isArray(p.airports) ? p.airports : [];
  if (list.length > 30) e.push('pricing.airports: at most 30.');
  const seen = new Set();
  list.forEach((a, i) => {
    const w = `pricing.airports[${i}]`;
    const n = String((a && a.name) || '').trim();
    if (!n) e.push(`${w}.name: required.`);
    else if (seen.has(n.toLowerCase())) e.push(`${w}.name: "${n}" is repeated.`);
    seen.add(n.toLowerCase());
    if (a && a.code && !CODE.test(a.code)) e.push(`${w}.code: 3 or 4 letters.`);
    const one = Number(a && a.one_way), ret = Number(a && a.return_fare);
    if (!(one >= 0.01 && one <= 10000)) e.push(`${w}.one_way: between 0.01 and 10,000.`);
    if (!(ret >= 0.01 && ret <= 20000)) e.push(`${w}.return_fare: between 0.01 and 20,000.`);
  });
  return e;
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const qn = (s) => (s && String(s).trim() ? q(String(s).trim()) : 'null');
const money = (n) => `£${Number(n).toFixed(2)}`;

function sql(c) {
  return `-- Generated by scripts/template/new-business.js. Review, then run once in the Supabase SQL editor.
-- Creates the business and its default notification settings. It changes nothing else.
-- Safe to read first: provision_tenant is service-role only and refuses a repeated slug.
select id, slug, name from public.provision_tenant(${q(c.slug)}, ${q(c.name.trim())}, ${qn(c.contact_email)}, ${qn(c.contact_phone)});
`;
}

function checklist(c) {
  const inv = c.invoice || {};
  const rows = (c.pricing && c.pricing.airports || []).map((a) => `| ${a.name} | ${a.code || ''} | ${money(a.one_way)} | ${money(a.return_fare)} |`).join('\n') || '| (none yet) | | | |';
  return `# Set up ${c.name.trim()} in the Operator app

Do these as the business's own admin (the person you invited), in order. Nothing here is automatic: each screen saves through the platform's own checked functions.

1. **Settings, Business**: name \`${c.name.trim()}\`; email \`${c.contact_email || ''}\`; phone \`${c.contact_phone || ''}\`.
   Invoice details: business name \`${inv.business_name || c.name.trim()}\`, address \`${inv.address || ''}\`, company number \`${inv.company_number || ''}\`, VAT number \`${inv.vat_number || ''}\`, licence \`${inv.licence || ''}\`.
2. **Settings, Prices**: extra stop ${money((c.pricing && c.pricing.extra_stop) || 0)}.

| Airport | Code | One way | Return |
|---|---|---|---|
${rows}

3. **Settings, Branding**: primary \`${(c.branding && c.branding.primary) || ''}\`, accent \`${(c.branding && c.branding.accent) || ''}\`; upload the logo (PNG, JPEG or WebP, up to 1 MB).
4. **Settings, Legal**: company details, cancellation policy, and tick the responsibilities confirmation (the business, not the platform, is responsible for licences, insurance, vehicles and driver checks).
5. **Settings, Payments**: connect the business's own Stripe account, **test mode first**.
6. **Drivers**: add drivers and invite them to the Driver App.
`;
}

function links(c) {
  const h = host(c.website);
  return `# Website, domain and links for ${c.name.trim()}

- Business short name: \`${c.slug}\`
- Website address to save (platform owner only, Operator app, Settings, Platform, Website address): \`${c.website || '(none yet)'}\`
- Driver App sign-in link: \`<driver-app-url>/login?b=${c.slug}\`
${h ? `
## Own domain (only when the business has bought one)

1. **Costs money on the hosting plan: ask the platform owner first.** Add \`${h}\` to the website's Vercel project and set DNS as Vercel says.
2. Add \`"${h}"\` to \`config/tenant-domains.json\` (no www, no https), run \`npm run build:domains\`, open a pull request, merge when the owner says merge, then deploy when the owner approves.
3. Test on the real domain: book, accept in the Operator app, pay in Stripe test mode, check the emails.
` : '\nNo website address yet: until one is saved the business is reached through the platform owner\'s own pages only.\n'}`;
}

function build(c) {
  const errors = validate(c);
  if (errors.length) return { errors };
  return { files: { '01-provision.sql': sql(c), '02-operator-app-checklist.md': checklist(c), '03-website-and-links.md': links(c) } };
}

function main(argv) {
  const [cfgPath, outArg] = argv;
  if (!cfgPath) { console.error('Usage: npm run new:business -- path/to/config.json [outDir]'); return 2; }
  let c;
  try { c = JSON.parse(fs.readFileSync(cfgPath, 'utf8')); } catch (err) { console.error(`Could not read ${cfgPath}: ${err.message}`); return 2; }
  const r = build(c);
  if (r.errors) { console.error('Fix these first:\n- ' + r.errors.join('\n- ')); return 1; }
  const out = outArg || path.join(__dirname, '..', '..', 'template', 'out', c.slug);
  fs.mkdirSync(out, { recursive: true });
  for (const [n, body] of Object.entries(r.files)) fs.writeFileSync(path.join(out, n), body);
  console.log(`Wrote ${Object.keys(r.files).length} files to ${out}. Nothing was sent or changed anywhere.`);
  return 0;
}

module.exports = { validate, build, sql, checklist, links };
if (require.main === module) process.exit(main(process.argv.slice(2)));
